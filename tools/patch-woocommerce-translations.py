#!/usr/bin/env python3
"""Merge the theme's storefront strings into the installed WooCommerce catalogue.

The Persian catalogue shipped with WooCommerce does not yet cover the block
cart/checkout screens or several account strings, so those pages fall back to
English on a Persian store. The theme cannot fix that with `load_textdomain()`
without hijacking WooCommerce's domain, so this script extends the catalogue the
plugin already loads instead.

Rules:
  * an existing translation always wins — nothing installed is overwritten;
  * only msgids that are missing or still English are added;
  * the result is written back as both .po (readable) and .mo (what WordPress reads).

Usage:
  tools/patch-woocommerce-translations.py [--check]

`--check` reports how many strings are still missing and changes nothing.
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ADDITIONS = ROOT / "tools" / "i18n" / "woocommerce-fa_IR.storefront.po"
LANG_DIR = ROOT / ".local" / "wordpress" / "wp-content" / "languages" / "plugins"
TARGET_PO = LANG_DIR / "woocommerce-fa_IR.po"

sys.path.insert(0, str(ROOT / "tools"))
import importlib.util

spec = importlib.util.spec_from_file_location("compile_po", ROOT / "tools" / "compile-po.py")
compile_po = importlib.util.module_from_spec(spec)
spec.loader.exec_module(compile_po)  # type: ignore[union-attr]


def read_existing(path: Path) -> dict[str, str]:
    return {msgid: msgstr for msgid, msgstr in compile_po.parse_po(path.read_text(encoding="utf-8"))}


def main() -> int:
    check_only = "--check" in sys.argv
    if not TARGET_PO.exists():
        print(f"missing catalogue: {TARGET_PO}", file=sys.stderr)
        return 1

    existing = read_existing(TARGET_PO)
    additions = [(i, s) for i, s in compile_po.parse_po(ADDITIONS.read_text(encoding="utf-8")) if i]

    missing = [(i, s) for i, s in additions if (existing.get(i, "") or "").strip() in ("", i)]
    print(f"catalogue holds {len(existing)} strings; {len(missing)} of {len(additions)} additions are needed")

    if check_only:
        for msgid, msgstr in missing[:8]:
            print(f"  missing: {msgid!r} -> {msgstr!r}")
        return 0 if not missing else 2

    if not missing:
        print("nothing to add")
        return 0

    merged = dict(existing)
    for msgid, msgstr in missing:
        merged[msgid] = msgstr

    # Keep the original header entry, then the merged body, sorted for stability.
    # Plural entries are written back with their msgid_plural line and indexed
    # msgstr[], otherwise a recompile silently loses every plural translation.
    header = existing.get("", "")

    def entry(msgid: str, msgstr: str) -> str:
        if "\x00" not in msgid:
            return f'msgid "{compile_po.escape_po(msgid)}"\nmsgstr "{compile_po.escape_po(msgstr)}"'
        singular, plural = msgid.split("\x00", 1)
        forms = msgstr.split("\x00")
        indexed = "\n".join(
            f'msgstr[{index}] "{compile_po.escape_po(form)}"' for index, form in enumerate(forms)
        )
        return (
            f'msgid "{compile_po.escape_po(singular)}"\n'
            f'msgid_plural "{compile_po.escape_po(plural)}"\n'
            f"{indexed}"
        )

    body = "\n\n".join(entry(msgid, merged[msgid]) for msgid in sorted(merged) if msgid)
    text = (
        "# Merged catalogue. Generated by tools/patch-woocommerce-translations.py\n"
        "# Installed translations are preserved; only missing storefront strings are added.\n"
        'msgid ""\n'
        f'msgstr "{compile_po.escape_po(header)}"\n\n'
        f"{body}\n"
    )
    TARGET_PO.write_text(text, encoding="utf-8")

    target_mo = TARGET_PO.with_suffix(".mo")
    target_mo.write_bytes(compile_po.compile_mo(list(merged.items())))
    print(f"wrote {TARGET_PO.name} and {target_mo.name} with {len(merged)} strings")
    return 0


if __name__ == "__main__":
    sys.exit(main())
