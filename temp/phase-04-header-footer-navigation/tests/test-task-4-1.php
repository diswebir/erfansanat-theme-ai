<?php
/**
 * Test Task 4.1 — header.php/footer.php cut from static with WP hooks + hreflang.
 * Run: php-wasm-cli temp/phase-04-header-footer-navigation/tests/test-task-4-1.php
 */
$THEME = dirname(__DIR__, 3);
$STATIC = '/tmp/shell_static.html';
$fail = 0;

function check(string $label, bool $cond): void {
    global $fail;
    echo ($cond ? "[PASS] " : "[FAIL] ") . $label . "\n";
    if (!$cond) { $fail++; }
}

$h = file_get_contents("$THEME/header.php") . file_get_contents("$THEME/footer.php") . file_get_contents("$THEME/inc/Nav/MegaMenuWalker.php");
$f = file_get_contents("$THEME/footer.php");
$static = file_get_contents($STATIC);

// WP standard calls present
foreach (['wp_head()', 'body_class()', 'wp_body_open()'] as $fn) {
    check("header.php calls $fn", strpos($h, $fn) !== false);
}
check('footer.php calls wp_footer()', strpos($f, 'wp_footer()') !== false);
check('header.php has language_attributes()', strpos($h, 'language_attributes()') !== false);

// 100% DOM preservation markers from the static header/footer
check('header keeps data-navbar-header attr', strpos($h, 'data-navbar-header') !== false);
check('header keeps mega menu triggers', strpos($h, 'data-desktop-mega-trigger') !== false);
check('header keeps mobile toggle hook', strpos($h, 'data-mobile-toggle') !== false);
check('header keeps search modal hook', strpos($h, 'data-search-modal-open') !== false);
check('footer keeps its root <footer tag', strpos($f, '<footer') !== false);

// static asset links removed from head (now enqueued via AssetManager)
check('static stylesheet link removed from header (enqueued instead)', strpos($h, '<link rel="stylesheet" href="assets/css/styles.css"') === false);
check('static main.js script tag removed from header', strpos($h, '<script src="assets/js/main.js"') === false);

// assets re-pointed to theme URI
check('asset URLs use ERFANSANAT_THEME_URI', strpos($h, 'ERFANSANAT_THEME_URI') !== false || strpos($f, 'ERFANSANAT_THEME_URI') !== false);

// hreflang in head
check('hreflang tags emitted (es_hreflang_tags)', strpos($h, 'es_hreflang_tags') !== false);
check('inc/Seo.php provides hreflang from hrefmeta_* meta', strpos(file_get_contents("$THEME/inc/Seo.php"), 'hrefmeta_fa') !== false);

// logo is dynamic from dashboard option
check('brand block (ESE) preserved from static', strpos($h, '>ESE<') !== false);

// shell-level data-* hooks (outside the dynamic nav/aside panels) must survive
$shellHooks = ['data-navbar-header','data-desktop-mega-trigger','data-mobile-toggle','data-search-modal-open','data-search-modal-close','data-cart-modal-open','data-mobile-menu','data-mobile-backdrop','data-mobile-sidebar','data-mobile-close','data-cart-modal-backdrop','data-cart-modal-close','data-scroll-top'];
$missing = 0;
foreach ($shellHooks as $hook) {
    if (strpos($h, $hook) === false) { $missing++; echo "  missing hook: $hook\n"; }
}
check('all shell data-* hooks preserved (panels are walker-generated)', $missing === 0);
// mega panel internals are generated by the walker, not hardcoded
$w = file_get_contents("$THEME/inc/Nav/MegaMenuWalker.php");
check('walker emits mega panel + tab hooks', strpos($w, 'data-mega-panel') !== false && strpos($w, 'data-mega-tab') !== false);

echo $fail === 0 ? "\nRESULT: ALL PASS\n" : "\nRESULT: $fail FAILURES\n";
exit($fail > 0 ? 1 : 0);
